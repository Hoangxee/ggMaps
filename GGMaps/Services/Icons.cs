    /// <summary>Maps Routes API maneuver names to an icon.</summary>
    public static class ManeuverIcons
    {
        public static string For(string maneuver, string travelMode)
        {
            switch (maneuver ?? "")
            {
                case "TURN_LEFT":
                case "TURN_SHARP_LEFT": return Icons.TurnLeft;
                case "TURN_RIGHT":
                case "TURN_SHARP_RIGHT": return Icons.TurnRight;
                case "TURN_SLIGHT_LEFT":
                case "RAMP_LEFT":
                case "FORK_LEFT": return Icons.SlightLeft;
                case "TURN_SLIGHT_RIGHT":
                case "RAMP_RIGHT":
                case "FORK_RIGHT": return Icons.SlightRight;
                case "UTURN_LEFT":
                case "UTURN_RIGHT": return Icons.UTurn;
                case "ROUNDABOUT_LEFT":
                case "ROUNDABOUT_RIGHT": return Icons.Roundabout;
                case "MERGE": return Icons.Merge;
                case "FERRY":
                case "FERRY_TRAIN": return Icons.Ferry;
                case "DESTINATION": return Icons.Flag;
            }
            if (travelMode == "WALK") return Icons.Walk;
            return Icons.Straight;
        }

        public static string ForMode(string mode)
        {
            switch (mode)
            {
                case "TWO_WHEELER": return Icons.Motorbike;
                case "TRANSIT": return Icons.Transit;
                case "WALK": return Icons.Walk;
                case "BICYCLE": return Icons.Bike;
                default: return Icons.Car;
            }
        }

        public static string ForVehicle(string vehicleType)
        {
            switch (vehicleType ?? "")
            {
                case "SUBWAY":
                case "METRO_RAIL":
                case "HEAVY_RAIL":
                case "COMMUTER_TRAIN":
                case "HIGH_SPEED_TRAIN":
                case "LONG_DISTANCE_TRAIN":
                case "RAIL":
                case "MONORAIL":
                case "TRAM": return Icons.Train;
                case "FERRY": return Icons.Ferry;
                default: return Icons.Transit;
            }
        }
    }
